<script>

document.addEventListener("DOMContentLoaded", function () {

    /* ======================================================
       MOBILE MENU
    ====================================================== */

    const toggle = document.querySelector(".gs-mobile-toggle");
    const close = document.querySelector(".gs-mobile-close");
    const menu = document.querySelector("#gs-mobile-menu");
    const overlay = document.querySelector("#gs-mobile-overlay");

    function openMenu() {

        if (!menu || !overlay) {
            return;
        }

        menu.classList.add("active");
        overlay.classList.add("active");

        if (toggle) {
            toggle.setAttribute(
                "aria-expanded",
                "true"
            );
        }

        menu.setAttribute(
            "aria-hidden",
            "false"
        );

        document.body.style.overflow = "hidden";
    }


    function closeMenu() {

        if (!menu || !overlay) {
            return;
        }

        menu.classList.remove("active");
        overlay.classList.remove("active");

        if (toggle) {
            toggle.setAttribute(
                "aria-expanded",
                "false"
            );
        }

        menu.setAttribute(
            "aria-hidden",
            "true"
        );

        document.body.style.overflow = "";
    }


    if (toggle) {
        toggle.addEventListener(
            "click",
            openMenu
        );
    }


    if (close) {
        close.addEventListener(
            "click",
            closeMenu
        );
    }


    if (overlay) {
        overlay.addEventListener(
            "click",
            closeMenu
        );
    }


    /* Close mobile menu after clicking a link */

    document
        .querySelectorAll(
            ".gs-mobile-links a, .gs-mobile-cta a"
        )
        .forEach(function (link) {

            link.addEventListener(
                "click",
                closeMenu
            );

        });


    /* ======================================================
       ESC KEY - CLOSE MOBILE MENU
    ====================================================== */

    document.addEventListener(
        "keydown",
        function (event) {

            if (event.key === "Escape") {
                closeMenu();
            }

        }
    );


    /* ======================================================
       HEADER SHADOW ON SCROLL
    ====================================================== */

    const header =
        document.querySelector(".gs-header");


    function updateHeader() {

        if (!header) {
            return;
        }

        if (window.scrollY > 20) {

            header.classList.add(
                "gs-header-scrolled"
            );

        } else {

            header.classList.remove(
                "gs-header-scrolled"
            );

        }

    }


    window.addEventListener(
        "scroll",
        updateHeader
    );

    updateHeader();


    /* ======================================================
       ACTIVE NAVIGATION
    ====================================================== */

    const sections =
        document.querySelectorAll(
            "main section[id]"
        );

    const navLinks =
        document.querySelectorAll(
            ".gs-navmenu a"
        );


    function updateActiveNav() {

        let current = "";

        sections.forEach(function (section) {

            const sectionTop =
                section.offsetTop - 150;

            const sectionHeight =
                section.offsetHeight;

            if (
                window.scrollY >= sectionTop &&
                window.scrollY <
                    sectionTop + sectionHeight
            ) {

                current = section.getAttribute("id");

            }

        });


        navLinks.forEach(function (link) {

            link.classList.remove("active");

            const href =
                link.getAttribute("href") || "";

            if (
                current &&
                href.includes("#" + current)
            ) {

                link.classList.add("active");

            }

        });

    }


    window.addEventListener(
        "scroll",
        updateActiveNav
    );


    /* ======================================================
       SMOOTH SCROLL
    ====================================================== */

    document
        .querySelectorAll(
            'a[href*="#"]'
        )
        .forEach(function (anchor) {

            anchor.addEventListener(
                "click",
                function (event) {

                    const href =
                        this.getAttribute("href");

                    if (!href) {
                        return;
                    }

                    const hashIndex =
                        href.indexOf("#");

                    if (hashIndex === -1) {
                        return;
                    }

                    const hash =
                        href.substring(hashIndex);

                    const target =
                        document.querySelector(hash);

                    if (target) {

                        event.preventDefault();

                        const headerHeight =
                            header
                                ? header.offsetHeight
                                : 0;

                        const targetPosition =
                            target.offsetTop -
                            headerHeight -
                            10;

                        window.scrollTo({
                            top: targetPosition,
                            behavior: "smooth"
                        });

                    }

                }
            );

        });


    /* ======================================================
       FOOTER YEAR
    ====================================================== */

    const yearElement =
        document.querySelector(
            "#gs-current-year"
        );

    if (yearElement) {

        yearElement.textContent =
            new Date().getFullYear();

    }

});

</script>


